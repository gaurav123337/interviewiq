#!/usr/bin/env node
/* gen-rag-corpus — generates supabase/functions/seed-rag/corpus.generated.ts from
   content/rag-seed/*.md.

   A deployed edge function can't read repo files at runtime, so the RAG starter
   corpus is baked into a committed .ts module that the seed-rag function statically
   imports (eszip bundles it at deploy, exactly as it does _shared/*.ts). This module
   holds RAW markdown only — all parsing/chunking lives in
   supabase/functions/_shared/ragSeed.ts.

   Run: npm run gen:rag-corpus   (re-run whenever a content/rag-seed/*.md changes; the
   src/__tests__/rag-corpus-gen.test.ts drift guard fails the build if you forget). */

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, relative } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CORPUS_DIR = join(ROOT, "content", "rag-seed");
const OUT_DIR = join(ROOT, "supabase", "functions", "seed-rag");
const OUT_FILE = join(OUT_DIR, "corpus.generated.ts");

const files = readdirSync(CORPUS_DIR).filter((f) => f.endsWith(".md")).sort();
if (files.length === 0) {
  console.error(`gen-rag-corpus: no .md files found in ${CORPUS_DIR}`);
  process.exit(1);
}

// LF-normalize the raw text so the committed module is byte-identical on Windows and
// Linux — the drift guard normalizes the same way, so CI passes regardless of the
// checkout's autocrlf setting. (ragSeed.ts also normalizes defensively at parse time.)
const entries = files.map((file) => ({
  file,
  raw: readFileSync(join(CORPUS_DIR, file), "utf8").replace(/\r\n/g, "\n"),
}));

const out = `/* AUTO-GENERATED by scripts/gen-rag-corpus.mjs — DO NOT EDIT BY HAND.
   Regenerate with: npm run gen:rag-corpus
   Source: content/rag-seed/*.md (${entries.length} files)

   Raw markdown baked in for the seed-rag edge function to statically import (a
   deployed function can't read repo files at runtime). Parsing/chunking lives in
   ../_shared/ragSeed.ts. */

export const RAG_SEED_CORPUS: { file: string; raw: string }[] = ${JSON.stringify(entries, null, 2)};
`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_FILE, out, "utf8");
console.log(`gen-rag-corpus: wrote ${relative(process.cwd(), OUT_FILE)} — ${entries.length} docs`);
